List<Exercise> seedExercises() {
  final all = <Exercise>[for (final p in seedRegionParts.values) ...p()];
  final rank = {
    for (var i = 0; i < _legacyOrder.length; i++) _legacyOrder[i]: i,
  };
  final idx = {for (var i = 0; i < all.length; i++) all[i].id: i};
  int key(Exercise e) => rank[e.id] ?? (_legacyOrder.length + idx[e.id]!);
  return all..sort((a, b) => key(a).compareTo(key(b)));
}
