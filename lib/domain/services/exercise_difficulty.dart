  /// The reviewed difficulty of built-in exercise [id], or null when [id] is not a built-in (custom exercise).
  static Difficulty? of(String id) {
    if (beginner.contains(id)) return Difficulty.beginner;
    if (intermediate.contains(id)) return Difficulty.intermediate;
    if (advanced.contains(id)) return Difficulty.advanced;
    return null;
  }

  /// Every classified id (tests).
  static Set<String> get all => {...beginner, ...intermediate, ...advanced};
