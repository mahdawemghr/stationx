/// Reviewed difficulty of every BUILT-IN exercise.
///
/// Difficulty answers "how likely is a newcomer to do this safely and well", NOT "how heavy" and NOT
/// "which equipment". Criteria used (any one can raise the level):
///  * technical complexity (olympic/ballistic lifts, loaded hinges from the floor, unilateral skill moves);
///  * strength prerequisite (strict one-arm / weighted / archer / ring / handstand variations);
///  * balance and stability demand (single-leg work, rings, kettlebell overhead/bottoms-up work);
///  * mobility demand (front squat, Z press, Cossack squat, Good Morning bar position);
///  * exercise-specific risk (sissy squat knee load, ab-wheel/dragon-flag lumbar load, deficit/snatch-grip pulls).
/// Equipment alone decides nothing: a bodyweight pistol squat is advanced, a push-up beginner; a hack squat
