/// Every id must be in exactly ONE set (test/domain/exercise_difficulty_test.dart enforces this and that
/// no set lists an id that does not exist), so adding an exercise forces a conscious decision.
/// Custom (user-made) exercises have NO entry: their difficulty is `null` (unspecified) and they are
